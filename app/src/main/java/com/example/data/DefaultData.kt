        )
    }

    /**
     * Idempotent first-run (and adult-list backfill) seed.
     *
     * Emptiness is decided from *all* lists, not just enabled ones: using the
     * enabled-only query re-inserted defaults whenever the user disabled every
     * list, REPLACE-resetting names/toggles and duplicating autogenerated targets.
     */
    suspend fun seedInto(
        listDao: BlockListDao,
        targetDao: BlockedTargetDao,
        scheduleDao: ScheduleDao,
        gardenDao: GardenPlantDao
    ) {
        seedMutex.withLock {
            val existing = listDao.getAllListsOnce()
            if (existing.isEmpty()) {
                for (list in defaultLists) {
                    listDao.insertList(list)
                }
                targetDao.insertTargets(defaultTargets)
                for (schedule in defaultSchedules) {
                    scheduleDao.insertSchedule(schedule)
                }
                gardenDao.insertPlant(welcomePlant())
                return@withLock
            }

            if (existing.none { isAdultList(it) }) {
                listDao.insertList(adultList)
                targetDao.insertTargets(targetsFor(adultListId))
            }
        }
    }

