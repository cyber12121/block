     * Serializes the Room-callback seed and the Application-level fallback so they
     * cannot both observe an empty table and insert a second copy of every target.
     * Targets use autogenerated primary keys, so a double insert is a silent duplicate
     * rather than a REPLACE.
     */
    val seedMutex = Mutex()

    val adultListId: Long = 6L

    fun isAdultList(list: BlockList): Boolean {
        return list.id == adultListId || list.name.contains("Adult", ignoreCase = true)
    }

    fun targetsFor(listId: Long): List<BlockedTarget> = defaultTargets.filter { it.listId == listId }

    val adultList: BlockList
        get() = defaultLists.first { it.id == adultListId }

    fun welcomePlant(nowMillis: Long = System.currentTimeMillis()): GardenPlant {
        return GardenPlant(
            plantType = PlantType.SPROUT,
            sessionMinutes = 25,
            plantedAtMillis = nowMillis - 86400000L,
            completedAtMillis = nowMillis - 85000000L,
            status = PlantStatus.BLOOMED,
